    // --- whole solves ---------------------------------------------------------------------
    //
    // The fixtures come from audiocraft's own `FlowModel.generate`, run against a stub
    // velocity field: `v = gain * (A * z + B * (1 + t))`, where `gain` is 1 for the
    // conditional branch and 0.5 for the unconditional one. Reproducing it here is a few
    // lines, and it makes every part of the loop that is *not* the DiT observable.
    {
        const size_t n = (size_t)SC * ST;
        const std::vector<float> prompt(solve_prompt, solve_prompt + n);

        // One branch of the stub field.
        auto branch = [&](const float* z, float t, float gain, float* out) {
            for (size_t i = 0; i < n; ++i)
                out[i] = gain * (solve_A[i] * z[i] + solve_B[i] * (1.0f + t));
        };
        // The same field with guidance folded in, which is what flow_solve is handed.
        auto field = [&](float cfg) {
            return [&, cfg](const float* z, float t, float* out) {
                // Guidance off means the inversion, whose only condition is `[""]` -- the
                // conditioner masks that out entirely, so the surviving branch is the
                // unconditional one and its gain is 0.5, not 1.
                if (cfg == 0.0f) { branch(z, t, 0.5f, out); return; }
                std::vector<float> uncond(n);
                branch(z, t, 1.0f, out);
                branch(z, t, 0.5f, uncond.data());
                for (size_t i = 0; i < n; ++i)
                    out[i] = (1.0f + cfg) * out[i] - cfg * uncond[i];
            };
        };
        // Replays a recorded noise stream, so both sides see identical draws.
        struct Replay {
            const float* data;
            size_t total, at = 0;
            void operator()(float* dst, size_t n) {
                if (at + n > total) throw std::runtime_error("noise stream exhausted");
                std::copy(data + at, data + at + n, dst);
                at += n;
            }
        };

        auto compare = [&](const char* what, const std::vector<float>& got,
                           const float* want, float tol) {
            check((int)got.size() == (int)n, what, (long long)got.size(), (long long)n);
            double worst = 0.0;
            for (size_t i = 0; i < n && i < got.size(); ++i) {
                const double err = std::fabs((double)got[i] - (double)want[i]);
                if (err > worst) worst = err;
                check_close(got[i], want[i], tol, what, (int)i);
            }
            std::printf("  %-22s max abs err %.3e\n", what, worst);
        };

        // The edit's second pass: guided, euler, no regularization.
        {
            ac::FlowParams p;
            p.steps = 3;
            p.source_flowstep = 0.12f;
            p.target_flowstep = 1.0f;
            p.cfg_coef = 4.0f;
            const std::vector<float> got =
                ac::flow_solve(p, prompt, SC, ST, field(p.effective_cfg_coef()));
            compare("solve guided", got, solve_guided_expected, 2e-5f);
        }

        // The edit's first pass: regularized inversion, guidance forced off. The recorded
        // stream is two draws per regularized iteration, one step's worth at a time.
        {
            ac::FlowParams p;
            p.steps = 3;
            p.source_flowstep = 1.0f;
            p.target_flowstep = 0.12f;
            p.regularize = true;
            p.regularize_iters = 2;
            p.keep_last_k_iters = 1;
            p.lambda_kl = 0.2f;
            check((int)(sizeof(solve_inverted_noise) / sizeof(float)) ==
                      SOLVE_INVERTED_DRAWS * SC * ST, "inverted noise stream length",
                  (long long)(sizeof(solve_inverted_noise) / sizeof(float)),
                  (long long)SOLVE_INVERTED_DRAWS * SC * ST);
            Replay replay{solve_inverted_noise, (size_t)SOLVE_INVERTED_DRAWS * n};
            const std::vector<float> got = ac::flow_solve(
                p, prompt, SC, ST, field(p.effective_cfg_coef()), std::ref(replay));
            compare("solve inverted", got, solve_inverted_expected, 1e-3f);
            check(replay.at == replay.total, "inverted noise fully consumed",
                  (long long)replay.at, (long long)replay.total);
        }

        // regularize_iters 4 / keep_last_k 2: two regularized iterations, so the moving
        // average actually averages -- weights 2/5 and 3/5.
        {
            ac::FlowParams p;
            p.steps = 3;
            p.source_flowstep = 1.0f;
            p.target_flowstep = 0.12f;
            p.regularize = true;
            p.regularize_iters = 4;
            p.keep_last_k_iters = 2;
            p.lambda_kl = 0.2f;
            Replay replay{solve_inverted4_noise, (size_t)SOLVE_INVERTED4_DRAWS * n};
            const std::vector<float> got = ac::flow_solve(
                p, prompt, SC, ST, field(p.effective_cfg_coef()), std::ref(replay));
            compare("solve inverted (4/2)", got, solve_inverted4_expected, 1e-3f);
            check(replay.at == replay.total, "inverted4 noise fully consumed",
                  (long long)replay.at, (long long)replay.total);
        }

        // How much of the residual above is genuine divergence, and how much is float32?
        //
        // The KL gradient goes through sign() and clip(), so a regularized solve is not a
        // smooth map. This measures how far the output moves when the input is nudged by
        // one part in 1e7 -- about the size of the gap between torch's float32 block
        // statistics and the double-precision ones computed here.
        //
        // At three steps the answer is ~1e-5, which is why the two fixtures above are
        // checked at 1e-3 rather than 1e-6. At terry's real 25 it is a few percent: the
        // inversion pass simply cannot be compared to torch element by element at that
        // depth, in any implementation, and docs/MELODYFLOW_EDIT.md says what is compared
        // instead. The generation pass has no KL term and stays smooth.
        {
            for (int steps : {3, 25}) {
                ac::FlowParams p;
                p.steps = steps;
                p.source_flowstep = 1.0f;
                p.target_flowstep = 0.12f;
                p.regularize = true;
                p.regularize_iters = 2;
                p.keep_last_k_iters = 1;
                p.lambda_kl = 0.2f;
                std::vector<float> nudged = prompt;
                for (size_t i = 0; i < n; ++i) nudged[i] *= 1.0f + 1e-7f;
                ac::Rng r1(99), r2(99);
                auto noise1 = [&](float* d, size_t m) { r1.fill_normal(d, m); };
                auto noise2 = [&](float* d, size_t m) { r2.fill_normal(d, m); };
                const std::vector<float> base =
                    ac::flow_solve(p, prompt, SC, ST, field(0.0f), noise1);
                const std::vector<float> moved =
                    ac::flow_solve(p, nudged, SC, ST, field(0.0f), noise2);
                double worst = 0.0, scale = 0.0;
                for (size_t i = 0; i < n; ++i) {
                    worst = std::max(worst, std::fabs((double)base[i] - (double)moved[i]));
                    scale = std::max(scale, std::fabs((double)base[i]));
                }
                std::printf("  regularized conditioning: %2d steps turn a 1e-7 input nudge "
                            "into %.1e relative\n", steps, worst / scale);
            }
        }

        // Midpoint: the even step stashes a half step, the odd one steps `gen` across both.
        {
            ac::FlowParams p;
            p.solver = ac::FlowSolverKind::Midpoint;
            p.steps = 4;
            p.source_flowstep = 0.12f;
            p.target_flowstep = 1.0f;
            p.cfg_coef = 4.0f;
            const std::vector<float> got =
                ac::flow_solve(p, prompt, SC, ST, field(p.effective_cfg_coef()));
            compare("solve midpoint", got, solve_midpoint_expected, 2e-5f);
        }

        // A zero field leaves the prompt exactly where it started, whatever the schedule.
        {
            ac::FlowParams p;
            p.steps = 25;
            p.source_flowstep = 0.12f;
            p.target_flowstep = 1.0f;
            const std::vector<float> got = ac::flow_solve(
                p, prompt, SC, ST,
                [&](const float*, float, float* out) { std::fill(out, out + n, 0.0f); });
            for (size_t i = 0; i < n; ++i)
                check_close(got[i], prompt[i], 0.0f, "zero field is a no-op", (int)i);
        }
    }

    // --- edit composition -------------------------------------------------------------
    {
        // terry's settings, as `MelodyFlow.edit` assembles them: an inversion down to the
        // flowstep with guidance off and regularization on, then a generation back up with
        // guidance on and regularization off.
        ac::EditParams e;
        const ac::FlowParams inv = ac::edit_inversion_params(e);
        const ac::FlowParams gen = ac::edit_generation_params(e);
        check(inv.source_flowstep == 1.0f, "inversion starts at 1.0",
              (long long)(inv.source_flowstep * 100), 100);
        check(inv.target_flowstep == e.target_flowstep, "inversion targets the flowstep",
              (long long)(inv.target_flowstep * 100), (long long)(e.target_flowstep * 100));
        check(inv.inverting(), "inversion integrates backwards", inv.inverting(), 1);
        check(inv.effective_cfg_coef() == 0.0f, "inversion drops guidance",
              (long long)inv.effective_cfg_coef(), 0);
        check(inv.regularize, "inversion regularizes", inv.regularize, 1);
        check(gen.source_flowstep == e.target_flowstep, "generation resumes at the flowstep",
              (long long)(gen.source_flowstep * 100), (long long)(e.target_flowstep * 100));
        check(gen.target_flowstep == 1.0f, "generation ends at 1.0",
              (long long)(gen.target_flowstep * 100), 100);
        check(!gen.regularize, "generation does not regularize", gen.regularize, 0);
        check(gen.effective_cfg_coef() == 4.0f, "generation keeps guidance at 4.0",
              (long long)gen.effective_cfg_coef(), 4);
        check(ac::edit_forward_count(e) == 125, "terry's edit costs 125 forwards",
              ac::edit_forward_count(e), 125);
    }

    // --- the configurations audiocraft does not guard, and we do ------------------------
    {
        const std::vector<float> tiny(4 * 4, 0.0f);
        auto zero = [](const float*, float, float* out) { *out = 0.0f; };
        auto threw = [&](ac::FlowParams p) {
            try {
                ac::flow_solve(p, tiny, 4, 4, zero,
                               [](float* d, size_t n) { std::fill(d, d + n, 0.0f); });
            } catch (const std::exception&) { return true; }
            return false;
        };
        ac::FlowParams p;
        p.steps = 2;
        p.regularize = true;
        p.regularize_iters = 1;
        p.keep_last_k_iters = 1;
        check(threw(p), "regularize_iters == keep_last_k_iters is rejected", threw(p), 1);
        p.regularize_iters = 2;
        p.keep_last_k_iters = 0;
        check(threw(p), "keep_last_k_iters == 0 is rejected", threw(p), 1);
        p.keep_last_k_iters = 1;
        p.solver = ac::FlowSolverKind::Midpoint;
        check(threw(p), "midpoint plus regularization is rejected", threw(p), 1);
    }

    if (failures) {
        std::fprintf(stderr, "%d check(s) failed\n", failures);
        return 1;
    }
    std::printf("solver_test: ok\n");
    return 0;
